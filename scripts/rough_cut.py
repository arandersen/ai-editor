#!/usr/bin/env python3
"""
rough_cut.py — The Finisher (FFmpeg Frame-Accurate Cutter, Zoomer & Audio Mixer)

Reads an Edit Decision List (EDL JSON) generated by Gemini 4 Argon from Parakeet
word-level timestamps, performs frame-accurate cuts with dynamic punch-in zooms,
applies 15ms audio crossfades to prevent clicks, optionally ducks background music,
and exports the edited MP4.

Example EDL JSON format:
{
  "music": "audio/music/track.mp3",
  "music_volume": 0.12,
  "segments": [
    {"start": 4.12, "end": 8.45, "zoom": 1.0,  "text": "I fully automated my video editing"},
    {"start": 9.10, "end": 14.80, "zoom": 1.10, "text": "using Gemini 4 Argon in Antigravity."}
  ]
}
"""

import argparse
import json
import os
import subprocess
import tempfile
from pathlib import Path


def run_cmd(cmd: list[str]) -> None:
    env = os.environ.copy()
    env["PATH"] = f"/opt/homebrew/bin:/usr/local/bin:{Path.home() / '.local/bin'}:{env.get('PATH', '')}"
    subprocess.run(cmd, check=True, env=env)


def build_edit(input_video: str, edl_path: str, output_video: str, draft: bool = False) -> None:
    with open(edl_path, "r", encoding="utf-8") as f:
        edl = json.load(f)

    segments = edl.get("segments", [])
    if not segments:
        raise ValueError(f"No segments found in EDL: {edl_path}")

    Path(output_video).parent.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as tmpdir:
        segment_files: list[str] = []
        concat_list_path = os.path.join(tmpdir, "segments.txt")

        for idx, seg in enumerate(segments):
            start = float(seg["start"])
            end = float(seg["end"])
            zoom = float(seg.get("zoom", 1.0))
            seg_out = os.path.join(tmpdir, f"seg_{idx:04d}.mp4")

            vf_filters = []
            if zoom > 1.001:
                # Anchor zoom slightly above center (y=42% of height) to preserve speaker eye-line (Rule #10)
                vf_filters.append(
                    f"scale=iw*{zoom}:ih*{zoom},crop=iw/{zoom}:ih/{zoom}:(iw-ow)/2:(ih-oh)*0.42"
                )
            vf_filters.append("format=yuv420p")
            vf_chain = ",".join(vf_filters)

            # Apply 15ms micro fade-in/out on audio to eliminate jump-cut clicks (Rule #34)
            dur = max(0.05, end - start)
            fade_out_start = max(0.0, dur - 0.015)
            af_chain = f"afade=t=in:st=0:d=0.015,afade=t=out:st={fade_out_start:.3f}:d=0.015"

            cmd = [
                "ffmpeg",
                "-y",
                "-ss",
                f"{start:.3f}",
                "-to",
                f"{end:.3f}",
                "-i",
                input_video,
                "-vf",
                vf_chain,
                "-af",
                af_chain,
                "-c:v",
                "libx264",
                "-preset",
                "veryfast" if draft else "fast",
                "-crf",
                "20" if draft else "17",
                "-c:a",
                "aac",
                "-b:a",
                "256k",
                "-loglevel",
                "error",
                seg_out,
            ]
            print(f"✂️  Cutting segment {idx + 1}/{len(segments)}: {start:.2f}s -> {end:.2f}s (zoom={zoom:.2f}x)")
            run_cmd(cmd)
            segment_files.append(seg_out)

        with open(concat_list_path, "w", encoding="utf-8") as lf:
            for seg_file in segment_files:
                lf.write(f"file '{seg_file}'\n")

        stitched_path = os.path.join(tmpdir, "stitched.mp4")
        print("🔗 Stitching segments and normalizing voice loudness (-14 LUFS)...")
        run_cmd(
            [
                "ffmpeg",
                "-y",
                "-f",
                "concat",
                "-safe",
                "0",
                "-i",
                concat_list_path,
                "-af",
                "highpass=f=80,loudnorm=I=-14:TP=-1.5:LRA=11",
                "-c:v",
                "copy",
                "-c:a",
                "aac",
                "-b:a",
                "320k",
                "-loglevel",
                "error",
                stitched_path,
            ]
        )

        music_path = edl.get("music")
        music_vol = float(edl.get("music_volume", 0.10))
        if music_path and os.path.exists(music_path):
            print(f"🎵 Mixing and ducking background music ({music_path})...")
            run_cmd(
                [
                    "ffmpeg",
                    "-y",
                    "-i",
                    stitched_path,
                    "-stream_loop",
                    "-1",
                    "-i",
                    music_path,
                    "-filter_complex",
                    f"[1:a]volume={music_vol}[bgm];[0:a][bgm]amix=inputs=2:duration=first:dropout_transition=2[aout]",
                    "-map",
                    "0:v",
                    "-map",
                    "[aout]",
                    "-c:v",
                    "copy",
                    "-c:a",
                    "aac",
                    "-b:a",
                    "320k",
                    "-shortest",
                    "-loglevel",
                    "error",
                    output_video,
                ]
            )
        else:
            os.replace(stitched_path, output_video)

    print(f"🎬 Finished! Output video saved to: {output_video}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Frame-accurate FFmpeg rough cutter and audio finisher")
    parser.add_argument("--input", required=True, help="Path to raw input video")
    parser.add_argument("--edl", required=True, help="Path to EDL JSON file")
    parser.add_argument("--output", required=True, help="Path to output MP4")
    parser.add_argument("--draft", action="store_true", help="Fast draft encoding mode")
    args = parser.parse_args()
    build_edit(args.input, args.edl, args.output, args.draft)


if __name__ == "__main__":
    main()
